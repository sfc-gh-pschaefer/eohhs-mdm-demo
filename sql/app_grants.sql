-- Caller grants for the App Runtime service owner (SYSADMIN), HESC pattern.
-- Pages run with restricted caller's rights, so policies apply to the signed-in
-- user. A caller grant gives no privilege; it lets the app use one the caller has.
-- SELECT is INHERITED so it covers tables REFRESH_MASTER recreates. Writes stay
-- table-specific. Rerun after run_pipeline.sh.
USE ROLE ACCOUNTADMIN;
GRANT CALLER USAGE ON WAREHOUSE EOHHS_WH TO ROLE SYSADMIN;

