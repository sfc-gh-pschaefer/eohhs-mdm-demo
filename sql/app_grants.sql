GRANT INHERITED CALLER SELECT ON ALL TABLES IN SCHEMA EOHHS_HUB.GOV TO ROLE SYSADMIN;
GRANT INHERITED CALLER SELECT ON ALL VIEWS IN SCHEMA EOHHS_HUB.GOV TO ROLE SYSADMIN;
GRANT CALLER SELECT, INSERT ON TABLE EOHHS_HUB.GOV.STEWARD_DECISIONS TO ROLE SYSADMIN;
