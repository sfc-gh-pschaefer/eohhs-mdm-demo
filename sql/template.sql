CREATE OR REPLACE PROCEDURE @@DB@@.MASTER_GOLD.REFRESH_MASTER()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE
  passes VARCHAR;
  masters INTEGER;
BEGIN
  CALL @@DB@@.INTEGRATION_SILVER.BUILD_CLUSTERS() INTO :passes;
  CREATE OR REPLACE TABLE @@DB@@.MASTER_GOLD.GOLDEN_RECORDS AS
  WITH m AS (
    SELECT l.label AS GOLDEN_ID, c.*,
      @@ID_RANK@@ AS ID_RANK, @@NAME_RANK@@ AS NAME_RANK, @@CONTACT_RANK@@ AS CONTACT_RANK
    FROM @@DB@@.INTEGRATION_SILVER.PERSON_CLEAN c JOIN @@DB@@.INTEGRATION_SILVER.LABELS l ON l.node = c.ROW_ID
  ),
  pick AS (
    SELECT GOLDEN_ID,
      MIN_BY(ROW_ID, QUALITY_SCORE * 1000 - ID_RANK) AS ROW_ID,
      MAX_BY(SSN, IFF(SSN IS NULL, NULL, -ID_RANK * 1e10 + DATE_PART(EPOCH, _LOAD_TS))) AS SSN,
      MAX_BY(SSN_LAST4, IFF(SSN_LAST4 IS NULL, NULL, -ID_RANK * 1e10 + DATE_PART(EPOCH, _LOAD_TS))) AS SSN_LAST4,
      MAX_BY(AGENCY_ID, IFF(AGENCY_ID IS NULL, NULL, -ID_RANK * 1e10 + DATE_PART(EPOCH, _LOAD_TS))) AS AGENCY_ID,
      MAX_BY(DOB_CLEAN, IFF(DOB_CLEAN IS NULL, NULL, -ID_RANK * 1e10 + DATE_PART(EPOCH, _LOAD_TS))) AS DOB_CLEAN,
      MAX_BY(FIRST_NAME_CLEAN, IFF(FIRST_NAME_CLEAN IS NULL, NULL, -NAME_RANK * 1e10 + DATE_PART(EPOCH, _LOAD_TS))) AS FIRST_NAME_CLEAN,
      MAX_BY(LAST_NAME_CLEAN, IFF(LAST_NAME_CLEAN IS NULL, NULL, -NAME_RANK * 1e10 + DATE_PART(EPOCH, _LOAD_TS))) AS LAST_NAME_CLEAN,
      MAX_BY(MIDDLE_NAME, IFF(NULLIF(MIDDLE_NAME, '') IS NULL, NULL, -NAME_RANK)) AS MIDDLE_NAME,
      MAX_BY(GENDER_CLEAN, IFF(GENDER_CLEAN IS NULL, NULL, -NAME_RANK)) AS GENDER_CLEAN,
      MAX_BY(ADDRESS_STREET_CLEAN, IFF(ADDRESS_STREET_CLEAN IS NULL, NULL, DATE_PART(EPOCH, _LOAD_TS))) AS ADDRESS_STREET_CLEAN,
      MAX_BY(ADDRESS_UNIT, IFF(ADDRESS_STREET_CLEAN IS NULL, NULL, DATE_PART(EPOCH, _LOAD_TS))) AS ADDRESS_UNIT,
      MAX_BY(ADDRESS_CITY, IFF(ADDRESS_STREET_CLEAN IS NULL, NULL, DATE_PART(EPOCH, _LOAD_TS))) AS ADDRESS_CITY,
      MAX_BY(ADDRESS_ZIP, IFF(ADDRESS_ZIP IS NULL, NULL, IFF(ADDRESS_STREET_CLEAN IS NOT NULL, 1e11, 0) + DATE_PART(EPOCH, _LOAD_TS))) AS ADDRESS_ZIP,
      MAX_BY(_SOURCE_SYSTEM, IFF(ADDRESS_STREET_CLEAN IS NULL, NULL, DATE_PART(EPOCH, _LOAD_TS))) AS ADDRESS_SOURCE,
      MAX(IFF(ADDRESS_STREET_CLEAN IS NULL, NULL, _LOAD_TS)) AS ADDRESS_AS_OF,
      MAX_BY(EMAIL_CLEAN, IFF(EMAIL_CLEAN IS NULL, NULL, -CONTACT_RANK * 1e10 + DATE_PART(EPOCH, _LOAD_TS))) AS EMAIL_CLEAN,
      MAX_BY(PHONE_CLEAN, IFF(PHONE_CLEAN IS NULL, NULL, -CONTACT_RANK * 1e10 + DATE_PART(EPOCH, _LOAD_TS))) AS PHONE_CLEAN,
      MAX_BY(TOKEN_SSN, IFF(TOKEN_SSN IS NULL, NULL, -ID_RANK)) AS TOKEN_SSN,
      MAX_BY(TOKEN_NAME_DOB, IFF(TOKEN_NAME_DOB IS NULL, NULL, -NAME_RANK)) AS TOKEN_NAME_DOB,
      MAX_BY(TOKEN_NAME_DOB_ZIP, IFF(TOKEN_NAME_DOB_ZIP IS NULL, NULL, DATE_PART(EPOCH, _LOAD_TS))) AS TOKEN_NAME_DOB_ZIP,
      LISTAGG(DISTINCT PROGRAM || ': ' || PROGRAM_STATUS, '; ') WITHIN GROUP (ORDER BY PROGRAM || ': ' || PROGRAM_STATUS) AS PROGRAMS,
      @@ACTIVE_EXPR@@ AS IS_ACTIVE,
      COUNT(*) AS CLUSTER_SIZE,
      COUNT(DISTINCT _SOURCE_SYSTEM) AS SOURCE_COUNT,
      LISTAGG(DISTINCT _SOURCE_SYSTEM, ', ') WITHIN GROUP (ORDER BY _SOURCE_SYSTEM) AS SOURCE_SYSTEMS,
      LISTAGG(DISTINCT SOURCE_RECORD_ID, ', ') WITHIN GROUP (ORDER BY SOURCE_RECORD_ID) AS SOURCE_RECORD_IDS,
      COUNT(DISTINCT SSN) AS DISTINCT_SSNS,
      COUNT(DISTINCT AGENCY_ID) AS DISTINCT_AGENCY_IDS,
      MAX(_LOAD_TS) AS LAST_UPDATED
    FROM m GROUP BY GOLDEN_ID
  )
  -- Full SSN never reaches gold: only last 4 and the salted token.
  SELECT '@@ID_PREFIX@@-' || LPAD(GOLDEN_ID::VARCHAR, 6, '0') AS MASTER_ID,
    p.* EXCLUDE (SSN),
    INITCAP(FIRST_NAME_CLEAN) || ' ' || INITCAP(LAST_NAME_CLEAN) AS DISPLAY_NAME,
    NULLIF(ARRAY_TO_STRING(ARRAY_CONSTRUCT_COMPACT(ADDRESS_STREET_CLEAN, 'APT ' || ADDRESS_UNIT, ADDRESS_CITY, ADDRESS_ZIP), ' '), '') AS ADDRESS_CLEAN,
    ROUND(100 * (IFF(SSN IS NOT NULL OR TOKEN_SSN IS NOT NULL, 3, 0) + IFF(AGENCY_ID IS NOT NULL, 2, 0) + IFF(DOB_CLEAN IS NOT NULL, 2, 0)
      + IFF(FIRST_NAME_CLEAN IS NOT NULL, 1, 0) + IFF(LAST_NAME_CLEAN IS NOT NULL, 1, 0)
      + IFF(ADDRESS_STREET_CLEAN IS NOT NULL, 1, 0) + IFF(ADDRESS_ZIP IS NOT NULL, 1, 0)
      + IFF(EMAIL_CLEAN IS NOT NULL, 1, 0) + IFF(PHONE_CLEAN IS NOT NULL, 1, 0)) / 13.0, 0) AS QUALITY_SCORE,
    CASE WHEN DISTINCT_SSNS > 1 THEN 'SSN conflict'
         WHEN DISTINCT_AGENCY_IDS > 1 THEN 'Duplicate @@AGENCY_ID_LABEL@@'
         WHEN SSN IS NULL AND TOKEN_SSN IS NULL AND CLUSTER_SIZE = 1 THEN 'Unverified identity'
         ELSE NULL END AS STEWARD_FLAG
  FROM pick p;
  CREATE OR REPLACE TABLE @@DB@@.MASTER_GOLD.XREF AS
  SELECT g.MASTER_ID, g.GOLDEN_ID, c.ROW_ID, c._SOURCE_SYSTEM, c.SOURCE_RECORD_ID,
    c.FIRST_NAME_AS_GIVEN, c.LAST_NAME_CLEAN, c.DOB_CLEAN, c.SSN_LAST4, c.AGENCY_ID, c.EMAIL_CLEAN, c.PHONE_CLEAN,
    c.ADDRESS_STREET_CLEAN, c.ADDRESS_ZIP, c.PROGRAM, c.PROGRAM_STATUS, c._LOAD_TS, c.QUALITY_SCORE,
    IFF(c.ROW_ID = g.ROW_ID, TRUE, FALSE) AS IS_ANCHOR
  FROM @@DB@@.INTEGRATION_SILVER.PERSON_CLEAN c
  JOIN @@DB@@.INTEGRATION_SILVER.LABELS l ON l.node = c.ROW_ID
  JOIN @@DB@@.MASTER_GOLD.GOLDEN_RECORDS g ON g.GOLDEN_ID = l.label;
  CREATE OR REPLACE TABLE @@DB@@.MASTER_GOLD.ALERTS AS
  @@ALERTS_SQL@@;
  UPDATE @@DB@@.INTEGRATION_SILVER.MATCH_RESULTS m
    SET ROUTING = 'AUTO_MERGE', MATCH_TYPE = 'TRANSITIVE',
        EVIDENCE = 'Already linked through other records in ' || xa.MASTER_ID || '. ' || COALESCE(m.EVIDENCE, '')
    FROM @@DB@@.MASTER_GOLD.XREF xa, @@DB@@.MASTER_GOLD.XREF xb
    WHERE m.ROUTING = 'MANUAL_REVIEW' AND xa.ROW_ID = m.ROW_A AND xb.ROW_ID = m.ROW_B AND xa.GOLDEN_ID = xb.GOLDEN_ID;
  @@AFTER_REFRESH@@
  SELECT COUNT(*) INTO :masters FROM @@DB@@.MASTER_GOLD.GOLDEN_RECORDS;
  RETURN masters || ' master records, clusters ' || passes;
END;
$$;

CALL @@DB@@.MASTER_GOLD.REFRESH_MASTER();
