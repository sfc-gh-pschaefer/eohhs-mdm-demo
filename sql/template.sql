-- Labels without the answer key: Tier 1 non-SSN merges are positives; SSN
-- conflicts and clearly different first names are negatives.
CREATE OR REPLACE TABLE ML_TRAINING AS
WITH pos AS (
  SELECT PAIR_FEATURES(a.FIRST_NAME_CLEAN, a.LAST_NAME_CLEAN, a.FIRST_NAME_AS_GIVEN, a.DOB_CLEAN, a.ADDRESS_ZIP, a.ADDRESS_STREET_CLEAN, a.SSN_LAST4, a.SSN, a.EMAIL_CLEAN, a.PHONE_CLEAN,
                       b.FIRST_NAME_CLEAN, b.LAST_NAME_CLEAN, b.FIRST_NAME_AS_GIVEN, b.DOB_CLEAN, b.ADDRESS_ZIP, b.ADDRESS_STREET_CLEAN, b.SSN_LAST4, b.SSN, b.EMAIL_CLEAN, b.PHONE_CLEAN) F,
         'MATCH' IS_MATCH
  FROM MATCH_RESULTS m JOIN PERSON_CLEAN a ON a.ROW_ID = m.ROW_A JOIN PERSON_CLEAN b ON b.ROW_ID = m.ROW_B
  WHERE m.MATCH_TYPE != 'T1_S0_SSN_CORROBORATED' AND a.FIRST_NAME_CLEAN IS NOT NULL AND b.FIRST_NAME_CLEAN IS NOT NULL
  QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(m.ROW_A, m.ROW_B)) <= 1000
),
neg AS (
  SELECT F, 'NO_MATCH' IS_MATCH FROM BLOCK_POOL
  WHERE (SSN_A IS NOT NULL AND SSN_B IS NOT NULL AND EDITDISTANCE(SSN_A, SSN_B) > 2)
     OR (F:FIRST_JW::FLOAT < 0.75 AND F:GIVEN_FIRST_EXACT::INT = 0)
  QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(ROW_ID_A, ROW_ID_B)) <= 1000
)
SELECT F:FIRST_JW::FLOAT FIRST_JW, F:LAST_JW::FLOAT LAST_JW, F:GIVEN_FIRST_EXACT::INT GIVEN_FIRST_EXACT,
       F:DOB_EXACT::INT DOB_EXACT, F:DOB_SWAPPED::INT DOB_SWAPPED, F:DOB_MISSING::INT DOB_MISSING,
       F:ZIP_EXACT::INT ZIP_EXACT, F:STREET_EXACT::INT STREET_EXACT, F:SSN4_EXACT::INT SSN4_EXACT,
       F:SSN4_CONFLICT::INT SSN4_CONFLICT, F:EMAIL_EXACT::INT EMAIL_EXACT, F:PHONE_EXACT::INT PHONE_EXACT, IS_MATCH
FROM (SELECT * FROM pos UNION ALL SELECT * FROM neg);

-- SNOWFLAKE.ML.CLASSIFICATION fails in this account ("must have an active
-- version defined"), so the same features and labels train a scikit-learn
-- gradient-boosting model inside Snowflake. Routing below is identical.
CREATE OR REPLACE PROCEDURE TRAIN_SCORE_ML()
RETURNS VARCHAR LANGUAGE PYTHON RUNTIME_VERSION = '3.11'
PACKAGES = ('snowflake-snowpark-python', 'scikit-learn') HANDLER = 'run' EXECUTE AS CALLER AS
$$
from sklearn.ensemble import GradientBoostingClassifier
F = ["FIRST_JW", "LAST_JW", "GIVEN_FIRST_EXACT", "DOB_EXACT", "DOB_SWAPPED", "DOB_MISSING", "ZIP_EXACT",
     "STREET_EXACT", "SSN4_EXACT", "SSN4_CONFLICT", "EMAIL_EXACT", "PHONE_EXACT"]
DB = "@@DB@@"

def run(session):
    train = session.table(f"{DB}.INTEGRATION_SILVER.ML_TRAINING").collect()
    X = [[float(r[f] or 0) for f in F] for r in train]
    y = [1 if r["IS_MATCH"] == "MATCH" else 0 for r in train]
    model = GradientBoostingClassifier(n_estimators=150, max_depth=3, random_state=42).fit(X, y)
    cand = session.sql(f"SELECT ROW_ID_A, ROW_ID_B, " + ", ".join(f"F:{f}::FLOAT {f}" for f in F)
                       + f" FROM {DB}.INTEGRATION_SILVER.ML_CANDIDATE_PAIRS").collect()
    probs = model.predict_proba([[float(r[f] or 0) for f in F] for r in cand])[:, 1] if cand else []
    session.sql(f"CREATE OR REPLACE TABLE {DB}.INTEGRATION_SILVER.ML_PROBS (ROW_ID_A NUMBER, ROW_ID_B NUMBER, P_MATCH FLOAT)").collect()
    if cand:
        session.create_dataframe([(int(r["ROW_ID_A"]), int(r["ROW_ID_B"]), float(p)) for r, p in zip(cand, probs)],
                                 schema=["ROW_ID_A", "ROW_ID_B", "P_MATCH"]).write.mode("append").save_as_table(f"{DB}.INTEGRATION_SILVER.ML_PROBS")
    imp = ",".join(f'"{k}":{round(float(v), 4)}' for k, v in sorted(zip(F, model.feature_importances_), key=lambda t: -t[1]))
    session.sql(f"CREATE OR REPLACE TABLE {DB}.GOV.ML_MODEL_INFO AS SELECT 'sklearn GradientBoostingClassifier' MODEL, "
                f"{len(train)} TRAIN_ROWS, {float(model.score(X, y))} TRAIN_ACC, PARSE_JSON('{{{imp}}}') FEATURE_IMPORTANCE, "
                f"CURRENT_TIMESTAMP() CREATED_AT").collect()
    return f"trained on {len(train)}, scored {len(cand)}"
$$;
CALL TRAIN_SCORE_ML();

CREATE OR REPLACE TABLE ML_ROUTED AS
SELECT s.*, p.P_MATCH,
  F:DOB_EXACT::INT + F:ZIP_EXACT::INT + F:STREET_EXACT::INT + F:SSN4_EXACT::INT
    + F:EMAIL_EXACT::INT + F:PHONE_EXACT::INT + IFF(F:LAST_JW::FLOAT >= 0.95, 1, 0) AS GUARD_FIELDS,
  CASE
    WHEN SSN_A IS NOT NULL AND SSN_B IS NOT NULL AND EDITDISTANCE(SSN_A, SSN_B) > 2 THEN 'AUTO_REJECT'
    WHEN F:SSN4_CONFLICT::INT = 1 THEN 'AUTO_REJECT'
    -- Address is never identity evidence on its own: refugees resettled through
    -- the same agency share its office address. One personal identifier must agree.
    WHEN P_MATCH >= 0.80 AND F:FIRST_JW::FLOAT >= 0.96 AND GUARD_FIELDS >= 3
     AND F:DOB_EXACT::INT + F:DOB_SWAPPED::INT + F:SSN4_EXACT::INT + F:EMAIL_EXACT::INT + F:PHONE_EXACT::INT >= 1 THEN 'AUTO_MERGE'
    WHEN P_MATCH >= 0.50 THEN 'MANUAL_REVIEW'
    WHEN F:FIRST_JW::FLOAT >= 0.92 AND F:LAST_JW::FLOAT >= 0.90 THEN 'MANUAL_REVIEW'
    ELSE 'AUTO_REJECT'
  END AS ROUTE
FROM ML_CANDIDATE_PAIRS s JOIN ML_PROBS p ON p.ROW_ID_A = s.ROW_ID_A AND p.ROW_ID_B = s.ROW_ID_B;

INSERT INTO MATCH_RESULTS
