CREATE OR REPLACE FUNCTION PAIR_FEATURES(
  fa VARCHAR, la VARCHAR, fga VARCHAR, da DATE, za VARCHAR, sa VARCHAR, s4a VARCHAR, ssna VARCHAR, ea VARCHAR, pa VARCHAR,
  fb VARCHAR, lb VARCHAR, fgb VARCHAR, db DATE, zb VARCHAR, sb VARCHAR, s4b VARCHAR, ssnb VARCHAR, eb VARCHAR, pb VARCHAR)
RETURNS OBJECT AS $$
  OBJECT_CONSTRUCT(
    'FIRST_JW', COALESCE(JAROWINKLER_SIMILARITY(fa, fb) / 100.0, 0),
    'LAST_JW', COALESCE(JAROWINKLER_SIMILARITY(la, lb) / 100.0, 0),
    'GIVEN_FIRST_EXACT', IFF(fga = fgb, 1, 0),
    'DOB_EXACT', IFF(da = db, 1, 0),
    'DOB_SWAPPED', IFF(da != db AND DAY(da) = MONTH(db) AND MONTH(da) = DAY(db) AND YEAR(da) = YEAR(db), 1, 0),
    'DOB_MISSING', IFF(da IS NULL OR db IS NULL, 1, 0),
    'ZIP_EXACT', IFF(za = zb, 1, 0),
    'STREET_EXACT', IFF(sa = sb, 1, 0),
    'SSN4_EXACT', IFF(s4a = s4b, 1, 0),
    'SSN4_CONFLICT', IFF(s4a IS NOT NULL AND s4b IS NOT NULL AND s4a != s4b, 1, 0),
    'SSN_EDIT_DISTANCE', IFF(ssna IS NOT NULL AND ssnb IS NOT NULL, EDITDISTANCE(ssna, ssnb), -1),
    'EMAIL_EXACT', IFF(ea = eb, 1, 0),
    'PHONE_EXACT', IFF(pa = pb, 1, 0))
$$;

CREATE OR REPLACE TABLE BLOCK_POOL AS
WITH r AS (
  SELECT c.*, l.label AS T1_CLUSTER FROM PERSON_CLEAN c JOIN T1_LABELS l ON l.node = c.ROW_ID
  WHERE c.FIRST_NAME_CLEAN IS NOT NULL AND c.LAST_NAME_CLEAN IS NOT NULL
