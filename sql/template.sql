  'p=' || ROUND(P_MATCH, 3) || ', guard fields=' || GUARD_FIELDS || ', first-name JW=' || ROUND(F:FIRST_JW::FLOAT, 2)
FROM ML_ROUTED WHERE ROUTE != 'AUTO_REJECT';

