CREATE OR REPLACE PROCEDURE @@DB@@.INTEGRATION_SILVER.BUILD_CLUSTERS()
RETURNS VARCHAR LANGUAGE SQL AS
$$
DECLARE
  changed INTEGER DEFAULT 1;
  passes INTEGER DEFAULT 0;
BEGIN
  CREATE OR REPLACE TABLE @@DB@@.INTEGRATION_SILVER.EDGES AS
    SELECT ROW_A src, ROW_B dst FROM @@DB@@.INTEGRATION_SILVER.MATCH_RESULTS WHERE ROUTING = 'AUTO_MERGE'
    UNION SELECT ROW_B, ROW_A FROM @@DB@@.INTEGRATION_SILVER.MATCH_RESULTS WHERE ROUTING = 'AUTO_MERGE';
  CREATE OR REPLACE TABLE @@DB@@.INTEGRATION_SILVER.LABELS AS
    SELECT ROW_ID node, ROW_ID label FROM @@DB@@.INTEGRATION_SILVER.PERSON_CLEAN;
  WHILE (changed > 0 AND passes < 30) DO
    CREATE OR REPLACE TEMPORARY TABLE @@DB@@.INTEGRATION_SILVER.LABELS_NEXT AS
      SELECT l.node, LEAST(l.label, COALESCE(MIN(n.label), l.label)) label
      FROM @@DB@@.INTEGRATION_SILVER.LABELS l
      LEFT JOIN @@DB@@.INTEGRATION_SILVER.EDGES e ON e.src = l.node
      LEFT JOIN @@DB@@.INTEGRATION_SILVER.LABELS n ON n.node = e.dst
      GROUP BY l.node, l.label;
    SELECT COUNT(*) INTO :changed FROM @@DB@@.INTEGRATION_SILVER.LABELS_NEXT x
      JOIN @@DB@@.INTEGRATION_SILVER.LABELS l ON l.node = x.node WHERE x.label != l.label;
    CREATE OR REPLACE TABLE @@DB@@.INTEGRATION_SILVER.LABELS AS SELECT * FROM @@DB@@.INTEGRATION_SILVER.LABELS_NEXT;
    passes := passes + 1;
  END WHILE;
  RETURN 'converged after ' || passes || ' passes';
END;
$$;

