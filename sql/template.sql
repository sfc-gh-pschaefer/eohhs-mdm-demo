pairs AS (
  SELECT a.ROW_ID A, b.ROW_ID B FROM r a JOIN r b ON a.DOB_CLEAN = b.DOB_CLEAN AND a.ROW_ID < b.ROW_ID
  WHERE JAROWINKLER_SIMILARITY(a.LAST_NAME_CLEAN, b.LAST_NAME_CLEAN) >= 80
     OR (JAROWINKLER_SIMILARITY(a.FIRST_NAME_CLEAN, b.FIRST_NAME_CLEAN) >= 90 AND a.ADDRESS_ZIP = b.ADDRESS_ZIP)
  UNION
  SELECT a.ROW_ID, b.ROW_ID FROM r a JOIN r b ON a.ADDRESS_ZIP = b.ADDRESS_ZIP AND a.ROW_ID < b.ROW_ID
  WHERE JAROWINKLER_SIMILARITY(a.LAST_NAME_CLEAN, b.LAST_NAME_CLEAN) >= 88 AND JAROWINKLER_SIMILARITY(a.FIRST_NAME_CLEAN, b.FIRST_NAME_CLEAN) >= 85
  UNION
  SELECT a.ROW_ID, b.ROW_ID FROM r a JOIN r b ON a.ROW_ID < b.ROW_ID AND a.LAST_NAME_CLEAN = b.LAST_NAME_CLEAN
   AND YEAR(a.DOB_CLEAN) = YEAR(b.DOB_CLEAN) AND DAY(a.DOB_CLEAN) = MONTH(b.DOB_CLEAN) AND MONTH(a.DOB_CLEAN) = DAY(b.DOB_CLEAN)
  UNION
  SELECT a.ROW_ID, b.ROW_ID FROM r a JOIN r b ON a.ROW_ID < b.ROW_ID AND a.LAST_NAME_CLEAN = b.LAST_NAME_CLEAN
   AND a.FIRST_NAME_CLEAN = b.FIRST_NAME_CLEAN AND (a.DOB_CLEAN IS NULL OR b.DOB_CLEAN IS NULL)
)
