CREATE OR REPLACE FUNCTION CLEAN_NAME(s VARCHAR)
RETURNS VARCHAR AS $$
  NULLIF(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(UPPER(s), '[^A-Z \\-]', ''), '\\s+', ' ')), '')
$$;
CREATE OR REPLACE FUNCTION CLEAN_STREET(s VARCHAR)
RETURNS VARCHAR AS $$
  NULLIF(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(
    REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(
      REGEXP_REPLACE(UPPER(s), '\\s*(APT\\.?|#|UNIT)\\s*[0-9A-Z]+$', ''),
    '[.,]', ''), '\\bSTREET\\b', 'ST'), '\\bAVENUE\\b', 'AVE'), '\\bROAD\\b', 'RD'),
    '\\bBOULEVARD\\b', 'BLVD'), '\\bDRIVE\\b', 'DR'), '\\bPLACE\\b', 'PL'), '\\bLANE\\b', 'LN'),
    '\\s+', ' ')), '')
$$;
CREATE OR REPLACE FUNCTION EXTRACT_UNIT(s VARCHAR)
RETURNS VARCHAR AS $$
  NULLIF(REGEXP_SUBSTR(UPPER(s), '(APT\\.?|#|UNIT)\\s*([0-9A-Z]+)$', 1, 1, 'e', 2), '')
$$;

