  a.FIRST_NAME_CLEAN FNAME_A, b.FIRST_NAME_CLEAN FNAME_B, a.LAST_NAME_CLEAN LNAME_A, b.LAST_NAME_CLEAN LNAME_B,
  a.FULL_NAME_CLEAN NAME_A, b.FULL_NAME_CLEAN NAME_B, a.DOB_CLEAN DOB_A, b.DOB_CLEAN DOB_B,
  a.ADDRESS_CLEAN ADDR_A, b.ADDRESS_CLEAN ADDR_B, a.ADDRESS_ZIP ZIP_A, b.ADDRESS_ZIP ZIP_B,
