-- ---------- 04 Tier 1 deterministic ----------
--  S0 (1.00) Full SSN + (DOB or last name or name/DOB token)   star topology
--  S1 (0.97) SSN last4 + DOB + first + last
--  S2 (0.96) Email + DOB
--  S3 (0.95) First + last + DOB + ZIP
--  S4 (0.94) Phone + DOB + first name         twin guard: twins share phone + DOB
--  S5 (0.90) JW(full) >= 94 + JW(first) >= 95 + DOB + ZIP + (street or last4)
-- No rule may merge two records whose full SSNs are both present and differ.
CREATE OR REPLACE TABLE MATCH_RESULTS AS
WITH r AS (SELECT * FROM PERSON_CLEAN WHERE @@T1_FILTER@@),
s0_hub AS (SELECT SSN, MIN(ROW_ID) AS HUB FROM r WHERE SSN IS NOT NULL GROUP BY SSN HAVING COUNT(*) > 1),
s0 AS (
  SELECT h.HUB AS ROW_A, r.ROW_ID AS ROW_B, 'T1_S0_SSN_CORROBORATED' AS MATCH_TYPE, 1.00 AS HYBRID_SCORE
  FROM s0_hub h JOIN r hr ON hr.ROW_ID = h.HUB
  JOIN r ON r.SSN = h.SSN AND r.ROW_ID > h.HUB
  WHERE r.DOB_CLEAN = hr.DOB_CLEAN OR r.LAST_NAME_CLEAN = hr.LAST_NAME_CLEAN OR r.TOKEN_NAME_DOB = hr.TOKEN_NAME_DOB
),
s1 AS (
  SELECT a.ROW_ID, b.ROW_ID, 'T1_S1_SSN4_DOB_NAME', 0.97
  FROM r a JOIN r b ON a.SSN_LAST4 = b.SSN_LAST4 AND a.DOB_CLEAN = b.DOB_CLEAN
   AND a.FIRST_NAME_CLEAN = b.FIRST_NAME_CLEAN AND a.LAST_NAME_CLEAN = b.LAST_NAME_CLEAN AND a.ROW_ID < b.ROW_ID
  WHERE NOT (a.SSN IS NOT NULL AND b.SSN IS NOT NULL AND a.SSN = b.SSN)
    AND NOT (a.SSN IS NOT NULL AND b.SSN IS NOT NULL AND EDITDISTANCE(a.SSN, b.SSN) > 2)
),
s2 AS (
  SELECT a.ROW_ID, b.ROW_ID, 'T1_S2_EMAIL_DOB', 0.96
  FROM r a JOIN r b ON a.EMAIL_CLEAN = b.EMAIL_CLEAN AND a.DOB_CLEAN = b.DOB_CLEAN AND a.ROW_ID < b.ROW_ID
  WHERE NOT (a.SSN IS NOT NULL AND b.SSN IS NOT NULL AND a.SSN != b.SSN)
),
s3 AS (
  SELECT a.ROW_ID, b.ROW_ID, 'T1_S3_NAME_DOB_ZIP', 0.95
  FROM r a JOIN r b ON a.FIRST_NAME_CLEAN = b.FIRST_NAME_CLEAN AND a.LAST_NAME_CLEAN = b.LAST_NAME_CLEAN
   AND a.DOB_CLEAN = b.DOB_CLEAN AND a.ADDRESS_ZIP = b.ADDRESS_ZIP AND a.ROW_ID < b.ROW_ID
  WHERE NOT (a.SSN IS NOT NULL AND b.SSN IS NOT NULL AND a.SSN != b.SSN)
