  a.PHONE_CLEAN PHONE_A, b.PHONE_CLEAN PHONE_B, a.FIRST_NAME_AS_GIVEN GIVEN_A, b.FIRST_NAME_AS_GIVEN GIVEN_B,
  a._SOURCE_SYSTEM SOURCE_A, b._SOURCE_SYSTEM SOURCE_B,
  ROUND(JAROWINKLER_SIMILARITY(a.FULL_NAME_CLEAN, b.FULL_NAME_CLEAN) / 100.0, 4) NAME_JW,
  PAIR_FEATURES(a.FIRST_NAME_CLEAN, a.LAST_NAME_CLEAN, a.FIRST_NAME_AS_GIVEN, a.DOB_CLEAN, a.ADDRESS_ZIP, a.ADDRESS_STREET_CLEAN, a.SSN_LAST4, a.SSN, a.EMAIL_CLEAN, a.PHONE_CLEAN,
                b.FIRST_NAME_CLEAN, b.LAST_NAME_CLEAN, b.FIRST_NAME_AS_GIVEN, b.DOB_CLEAN, b.ADDRESS_ZIP, b.ADDRESS_STREET_CLEAN, b.SSN_LAST4, b.SSN, b.EMAIL_CLEAN, b.PHONE_CLEAN) F
FROM pairs p JOIN r a ON a.ROW_ID = p.A JOIN r b ON b.ROW_ID = p.B;

