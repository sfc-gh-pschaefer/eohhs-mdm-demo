CREATE OR REPLACE VIEW @@DB@@.GOV.MATCH_QUALITY_SCORECARD AS
WITH gt AS (
  SELECT x.ROW_ID, x.GOLDEN_ID, g.RESIDENT_ID
  FROM @@DB@@.MASTER_GOLD.XREF x JOIN @@GROUND_TRUTH@@ g
    ON g.SOURCE_SYSTEM = x._SOURCE_SYSTEM AND g.SOURCE_RECORD_ID = x.SOURCE_RECORD_ID
),
pred AS (SELECT GOLDEN_ID, RESIDENT_ID, COUNT(*) n FROM gt GROUP BY 1, 2),
tp AS (SELECT SUM(n * (n - 1) / 2) v FROM pred),
pp AS (SELECT SUM(c * (c - 1) / 2) v FROM (SELECT GOLDEN_ID, COUNT(*) c FROM gt GROUP BY 1)),
ap AS (SELECT SUM(c * (c - 1) / 2) v FROM (SELECT RESIDENT_ID, COUNT(*) c FROM gt GROUP BY 1))
SELECT
  (SELECT COUNT(*) FROM @@DB@@.INTEGRATION_SILVER.PERSON_CLEAN) AS SOURCE_RECORDS,
  (SELECT COUNT(*) FROM @@DB@@.MASTER_GOLD.GOLDEN_RECORDS) AS MASTER_RECORDS,
  (SELECT COUNT(DISTINCT RESIDENT_ID) FROM gt) AS TRUE_PERSONS,
  ROUND(100.0 * tp.v / NULLIF(pp.v, 0), 2) AS PRECISION_PCT,
  ROUND(100.0 * tp.v / NULLIF(ap.v, 0), 2) AS RECALL_PCT,
  pp.v - tp.v AS FALSE_MERGE_PAIRS,
  (SELECT COUNT(*) FROM (SELECT GOLDEN_ID FROM pred GROUP BY 1 HAVING COUNT(*) > 1)) AS MASTERS_WITH_FALSE_MERGE,
  (SELECT COUNT(*) FROM @@DB@@.INTEGRATION_SILVER.MATCH_RESULTS WHERE ROUTING = 'MANUAL_REVIEW') AS PENDING_REVIEW,
  (SELECT ROUND(100.0 * COUNT_IF(NOT (a.SSN IS NOT NULL AND a.SSN = b.SSN)) / NULLIF(COUNT(*), 0), 1)
     FROM @@DB@@.INTEGRATION_SILVER.MATCH_RESULTS m JOIN @@DB@@.INTEGRATION_SILVER.PERSON_CLEAN a ON a.ROW_ID = m.ROW_A
     JOIN @@DB@@.INTEGRATION_SILVER.PERSON_CLEAN b ON b.ROW_ID = m.ROW_B WHERE m.ROUTING = 'AUTO_MERGE') AS LINKS_WITHOUT_SSN_PCT,
  (SELECT COUNT(*) FROM (SELECT x.GOLDEN_ID FROM @@DB@@.MASTER_GOLD.XREF x JOIN @@DB@@.INTEGRATION_SILVER.PERSON_CLEAN c ON c.ROW_ID = x.ROW_ID
     GROUP BY 1 HAVING COUNT(c.SSN) = 0 AND COUNT(*) > 1)) AS MASTERS_RESOLVED_WITHOUT_SSN,
  CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS SCORED_AT
FROM tp, pp, ap;

